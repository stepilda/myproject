  var LABELS = { en: "English", ta: "தமிழ்", hi: "हिन्दी" };

  function currentLang() {
    var stored = localStorage.getItem("agrilink_lang");
    return I18N[stored] ? stored : "en";
  }

  function t(key) {
    var lang = currentLang();
    return (I18N[lang] && I18N[lang][key]) || (I18N.en[key] || key);
  }

  function applyLang(lang) {
    if (!I18N[lang]) lang = "en";
    localStorage.setItem("agrilink_lang", lang);
    document.documentElement.lang = lang === "ta" ? "ta" : (lang === "hi" ? "hi" : "en");
    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      el.textContent = t(el.getAttribute("data-i18n"));
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach(function (el) {
      el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder")));
    });
    document.querySelectorAll("[data-i18n-html]").forEach(function (el) {
      el.innerHTML = t(el.getAttribute("data-i18n-html"));
    });
    var label = document.getElementById("langLabel");
    if (label) label.textContent = LABELS[lang] || "English";
    document.querySelectorAll(".lang-option").forEach(function (btn) {
      btn.classList.toggle("active", btn.getAttribute("data-lang") === lang);
    });
    document.dispatchEvent(new CustomEvent("agrilink:lang", { detail: lang }));
  }

  function bindLangSwitcher() {
    document.querySelectorAll(".lang-option").forEach(function (btn) {
      btn.addEventListener("click", function () {
        applyLang(btn.getAttribute("data-lang"));
      });
    });
    applyLang(currentLang());
  }

  function leaves() {
    var wrap = document.querySelector(".leaf-fall");
    if (!wrap) return;
    var glyphs = ["🍃", "🌿", "🌾"];
    for (var i = 0; i < 10; i++) {
      var s = document.createElement("span");
      s.textContent = glyphs[i % glyphs.length];
      s.style.left = (Math.random() * 100) + "%";
      s.style.animationDuration = (10 + Math.random() * 12) + "s";
      s.style.animationDelay = (-Math.random() * 12) + "s";
      wrap.appendChild(s);
    }
  }

  global.AgriI18n = { t: t, applyLang: applyLang, bindLangSwitcher: bindLangSwitcher, currentLang: currentLang, labels: LABELS };
  document.addEventListener("DOMContentLoaded", function () {
    bindLangSwitcher();
    leaves();
  });
